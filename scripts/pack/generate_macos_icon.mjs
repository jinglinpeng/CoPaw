#!/usr/bin/env node
// Regenerate the ICNS used by both Tauri and rollback macOS bundles.
// The Tauri macOS build invokes this after installing console dependencies.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const assets = fileURLToPath(new URL("./assets/", import.meta.url));
const consoleDir = fileURLToPath(new URL("../../console/", import.meta.url));
const cli = path.join(consoleDir, "node_modules/@tauri-apps/cli/tauri.js");
const svg = readFileSync(path.join(assets, "icon.svg"), "utf8");
const viewBox = 'viewBox="0 0 1024 1024"';
if (!svg.includes(viewBox)) {
  throw new Error(
    "Expected a 1024px source viewBox; review the macOS padding before regenerating.",
  );
}

// Legacy ICNS artwork needs transparent margins; the shared source is full
// bleed. Keep its rounded square centered at 80% of the icon canvas.
const padded = svg.replace(viewBox, 'viewBox="-128 -128 1280 1280"');
const temporary = mkdtempSync(path.join(tmpdir(), "qwenpaw-macos-icon-"));
try {
  const input = path.join(temporary, "macos.svg");
  const output = path.join(temporary, "icons");
  writeFileSync(input, padded);
  execFileSync(process.execPath, [cli, "icon", input, "--output", output], {
    cwd: consoleDir,
    stdio: "inherit",
  });
  // The CLI emits ICNS chunks in unspecified order. Sort them so repeated
  // generation produces identical bytes and a reviewable asset checksum.
  const generated = readFileSync(path.join(output, "icon.icns"));
  const chunks = [];
  for (let offset = 8; offset < generated.length; ) {
    const length = generated.readUInt32BE(offset + 4);
    if (length < 8 || offset + length > generated.length) {
      throw new Error("Invalid ICNS chunk generated by the Tauri CLI");
    }
    chunks.push(generated.subarray(offset, offset + length));
    offset += length;
  }
  chunks.sort((a, b) => Buffer.compare(a.subarray(0, 4), b.subarray(0, 4)));
  writeFileSync(
    path.join(assets, "icon.icns"),
    Buffer.concat([generated.subarray(0, 8), ...chunks]),
  );
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
